# =============================================================================
# POST /auth/register — 用户注册
# =============================================================================
"""
POST /auth/register

描述: 注册新用户，自动登录并返回令牌。

请求体 (JSON):
{
    "username": "zhangsan",   // 必填，至少 3 字符
    "password": "abc123"      // 必填，至少 6 字符
}

成功响应 (200):
{
    "code": 0,
    "message": "success",
    "data": {
        "user": {
            "id": 2,
            "username": "zhangsan",
            "role": "user",
            "created_at": "2026-07-15T10:00:00Z"
        },
        "token": "eyJhbGc..."
    }
}

错误 (400):
{
    "code": 1,
    "message": "用户名至少需要 3 个字符"
}
"""


# =============================================================================
# POST /auth/login — 用户登录
# =============================================================================
"""
POST /auth/login

描述: 用户登录验证，成功返回 JWT 令牌。

请求体 (JSON):
{
    "username": "admin",
    "password": "admin123"
}

成功响应 (200): 同 register
错误 (401):
{
    "code": 401,
    "message": "用户名或密码错误"
}
"""


# =============================================================================
# GET /auth/me — 获取当前用户
# =============================================================================
"""
GET /auth/me

描述: 获取当前登录用户信息。

请求头:
    Authorization: Bearer <token>

成功响应 (200):
{
    "code": 0,
    "data": {
        "id": 1,
        "username": "admin",
        "role": "admin",
        "created_at": "2026-01-01T00:00:00Z"
    }
}

未登录 (401):
{
    "code": 401,
    "message": "未登录或令牌无效"
}
"""


# =============================================================================
# POST /auth/token/verify — 验证令牌
# =============================================================================
"""
POST /auth/token/verify

描述: 验证令牌有效性。

请求体 (JSON):
{
    "token": "eyJhbGc..."
}

成功响应 (200):
{
    "code": 0,
    "data": {
        "user_id": 1,
        "username": "admin",
        "role": "admin",
        "exp": 1752537600,
        "iat": 1751932800
    }
}
"""
