# GET /nodes — 获取节点列表
# =============================================================================
"""
GET /nodes

描述: 分页获取长征节点列表，仅返回 status=active 的节点。

Query 参数:
    page        int   页码，从 1 开始，默认 1
    per_page    int   每页数量，默认 20，最大 100
    search      str   关键词，模糊匹配 title 和 location
    province    str   省份名称过滤（如 "贵州"）

响应示例 (200):
{
    "code": 0,
    "message": "success",
    "data": {
        "items": [
            {
                "node_id": "001",
                "title": "瑞金",
                "location": "江西省瑞金市",
                "lat": 25.8833,
                "lng": 116.0200,
                "time": "1934年10月",
                "core_numbers": "中央红军",
                "famous_battle": "...",
                "status": "active",
                "created_at": "2026-01-01T00:00:00Z",
                "image_list": []
            }
        ],
        "total": 50,
        "page": 1,
        "per_page": 20,
        "pages": 3
    }
}
"""


