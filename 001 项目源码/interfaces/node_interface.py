# =============================================================================
# POST /nodes — 创建节点（管理员）
# =============================================================================
"""
POST /nodes

描述: 创建一个新的长征节点（需管理员权限）。

权限: 需要 admin 或 super 角色

请求体 (JSON):
{
    "node_id": "051",           // 必填，节点编号（唯一）
    "title": "腊子口",          // 必填
    "location": "甘肃省迭部县",  // 必填
    "lat": 34.0567,             // 必填
    "lng": 103.6821,            // 必填
    "time": "1935年9月",        // 必填
    "core_numbers": "中央红军",
    "famous_battle": "腊子口战役",
    "history_event": "...",
    "historical_significance": "...",
    // ... 其他可选字段
}

响应 (201):
{
    "code": 0,
    "message": "success",
    "data": { ...新节点对象 }
}
"""


# =============================================================================
# PUT /nodes/<node_id> — 更新节点（管理员）
# =============================================================================
"""
PUT /nodes/<node_id>

描述: 更新指定节点的字段（部分更新，传入什么更新什么）。

权限: 需要 admin 或 super 角色

请求体 (JSON): 任意字段组合
响应 (200): 返回更新后的完整节点对象
"""


# =============================================================================
# DELETE /nodes/<node_id> — 删除节点（管理员）
# =============================================================================
"""
DELETE /nodes/<node_id>

描述: 软删除节点（将 status 改为 archived）。

权限: 需要 admin 或 super 角色

Query 参数:
    hard    bool   true=永久删除，默认 false

响应 (200):
{
    "code": 0,
    "message": "节点已删除"
}
"""


# =============================================================================
