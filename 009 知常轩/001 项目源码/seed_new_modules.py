    if empty > 0:
        base = datetime.date(2026, 8, 18)
        for i in range(1, empty + 1):
            cur.execute('UPDATE daily_saying SET date=? WHERE id=? AND date IS NULL',
                        (base + datetime.timedelta(days=i - 1), i))
        print('每日一句分配日期:', empty, '条')
    conn.commit()
    conn.close()
    print('本次入库文章:', total, '篇')


