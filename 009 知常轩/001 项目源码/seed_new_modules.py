    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    total = 0
    empty = set()
    for mid in (9, 10, 11, 12):
        n = cur.execute('SELECT COUNT(*) FROM article WHERE module_id=?', (mid,)).fetchone()[0]
        if n > 0:
            print('模块', mid, '已有文章', n, '篇,跳过')
        else:
            empty.add(mid)
    for a in ARTICLES:
        mid = a['module_id']
        if mid not in empty:
            continue
        cur.execute('''INSERT INTO article
            (title, module_id, column_name, content, original_text, annotation, translation,
             tags, age_level, status, author_id, published_at)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?)''',
            (a['title'], mid, a['column_name'], a['content'],
             None, None, None, a['tags'], a['age_level'], 1, 1, now))
        total += 1
    # 每日一句补 date:仅当 date 全空时,按 id 顺序分配 2026-08-18 起 8 天
