def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute('SELECT COUNT(*) FROM article WHERE module_id=4')
    if cur.fetchone()[0] > 0:
        print('书法文化模块已有文章，跳过')
        conn.close()
        return
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    for a in ARTICLES:
        cur.execute('''INSERT INTO article
            (title, module_id, column_name, content, original_text, annotation, translation,
             tags, age_level, status, author_id, published_at)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?)''',
            (a['title'], a['module_id'], a['column_name'], a['content'],
             a.get('original_text'), a.get('annotation'), a.get('translation'),
             a['tags'], a['age_level'], a['status'], a['author_id'], now))
    conn.commit()
    conn.close()
    print('书法文化模块入库:', len(ARTICLES), '篇')


if __name__ == '__main__':
    main()
