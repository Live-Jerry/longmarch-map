def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    total = 0
    for a in ARTICLES:
        exists = cur.execute(
            'SELECT id FROM article WHERE module_id=? AND column_name=? AND title=?',
            (a['module_id'], a['column_name'], a['title'])).fetchone()
        if exists:
            print('已存在,跳过:', a['title'])
            continue
        cur.execute('''INSERT INTO article
            (title, module_id, column_name, content, original_text, annotation, translation,
             tags, age_level, status, author_id, published_at)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?)''',
            (a['title'], a['module_id'], a['column_name'], a['content'],
             None, None, None, a['tags'], a['age_level'], 1, 1, now))
        total += 1
        print('入库:', a['title'])
    conn.commit()
    conn.close()
    print('本次入库文章:', total, '篇')


if __name__ == '__main__':
    main()
